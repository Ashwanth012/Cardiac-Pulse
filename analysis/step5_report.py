def figures(R, fig_dir):
    os.makedirs(fig_dir, exist_ok=True)
    p = lambda n: os.path.join(fig_dir, n)  # noqa: E731
    pc = R["per_cutoff"]

    fig, ax = plt.subplots(figsize=(10, 3.8))
    ax.plot(pc.index, pc["MAE_B0"], color=MUTED, marker="o", markersize=4, label="seasonal naive (harness baseline)")
    ax.plot(pc.index, pc["MAE"], color=BLUE, marker="o", markersize=4, label="M4 (forecast.py)")
    ax.set_ylim(0, max(pc.MAE.max(), pc.MAE_B0.max()) * 1.15)
    ax.set_ylabel("14-day MAE")
    ax.set_title("Holdout error at each cut-off (Jan-Mar 2019, primary 4-day grid)")
    ax.legend(loc="upper right")
    _save(fig, p("fig01_holdout_mae_by_cutoff.png"), "Each point = one cut-off's 14-day window. Forecasts by the frozen forecast.py in a fresh process.")

    P = R["P"]
    cuts = sorted(P.cutoff.unique())
    picks = [cuts[0], cuts[len(cuts) // 3], cuts[2 * len(cuts) // 3], cuts[-1]]
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.4), sharey=True)
    for ax, c in zip(axes, picks):
        s = P[P.cutoff == c]
        ax.fill_between(s.date, s.lo, s.hi, color=BLUE, alpha=0.18, linewidth=0)
        ax.plot(s.date, s["mean"], color=BLUE, label="M4 mean")
        ax.plot(s.date, s.b0, color=MUTED, linewidth=1.2, label="seasonal naive")
        ax.plot(s.date, s.y, "o", color=INK, markersize=3.5, label="actual")
        ax.set_title(f"cut-off {pd.Timestamp(c).date()}", fontsize=9)
        ax.tick_params(axis="x", rotation=45, labelsize=7)
    axes[0].set_ylabel("admissions")
    axes[0].legend(loc="upper left", fontsize=7)
    _save(fig, p("fig02_holdout_example_forecasts.png"), "Shaded = M4 80% interval.")

    bh = R["by_h"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.4))
    axes[0].plot(bh.index, bh.MAE_B0, color=MUTED, marker="o", markersize=4, label="seasonal naive")
    axes[0].plot(bh.index, bh.MAE, color=BLUE, marker="o", markersize=4, label="M4")
    axes[0].set_ylim(0, None)
    axes[0].set_xlabel("horizon (days, 1 = cut-off day)")
    axes[0].set_ylabel("MAE")
    axes[0].legend(loc="lower right")
    axes[0].set_title("Error by horizon")
    axes[1].bar(bh.index, 100 * bh.coverage80, color=BLUE, width=0.6)
    axes[1].axhline(80, color=ORANGE, linestyle=":")
    axes[1].text(14.4, 80, "80%", color=INK2, fontsize=8, va="center")
    axes[1].set_ylim(0, 105)
    axes[1].set_xlabel("horizon")
    axes[1].set_ylabel("coverage (%)")
    axes[1].set_title(f"M4 80% interval coverage by horizon (n = {R['per_cutoff'].shape[0]} per bar)")
    axes[1].grid(axis="x", visible=False)
    _save(fig, p("fig03_holdout_by_horizon.png"), "Each horizon has only one value per cut-off, so per-horizon coverage is noisy.")
    return sorted(os.listdir(fig_dir))


def _md(df, fmt="{:.3f}"):
    head = "| " + " | ".join([str(df.index.name or "")] + [str(c) for c in df.columns]) + " |"
    lines = [head, "|" + "---|" * (len(df.columns) + 1)]
    for i, row in df.iterrows():
        cells = [fmt.format(v) if isinstance(v, (float, np.floating)) and not pd.isna(v) else ("" if pd.isna(v) else str(v)) for v in row]
        lines.append("| " + " | ".join([str(i)] + cells) + " |")
    return "\n".join(lines)


